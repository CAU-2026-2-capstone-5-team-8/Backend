CREATE TABLE book_ranking_v2_projection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id bigint NOT NULL,
    topic_id bigint NOT NULL,
    version varchar(80) NOT NULL CHECK (btrim(version) <> ''),
    active boolean NOT NULL DEFAULT false,
    topic_distribution jsonb NOT NULL CHECK (jsonb_typeof(topic_distribution) = 'object'),
    covered_concepts jsonb NOT NULL CHECK (jsonb_typeof(covered_concepts) = 'array'),
    prerequisite_concepts jsonb NOT NULL CHECK (jsonb_typeof(prerequisite_concepts) = 'array'),
    lexical_difficulty double precision CHECK (lexical_difficulty BETWEEN 0 AND 1),
    syntactic_complexity double precision CHECK (syntactic_complexity BETWEEN 0 AND 1),
    concept_density double precision CHECK (concept_density BETWEEN 0 AND 1),
    prerequisite_demand double precision CHECK (prerequisite_demand BETWEEN 0 AND 1),
    config_version varchar(80) NOT NULL CHECK (btrim(config_version) <> ''),
    config_hash varchar(71) NOT NULL CHECK (config_hash ~ '^sha256:[0-9a-f]{64}$'),
    source_artifact_version varchar(120) NOT NULL CHECK (btrim(source_artifact_version) <> ''),
    source_artifact_hash varchar(71) NOT NULL CHECK (source_artifact_hash ~ '^sha256:[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (book_id, topic_id) REFERENCES book_topic(book_id, topic_id),
    UNIQUE (book_id, topic_id, version)
);
CREATE UNIQUE INDEX book_ranking_v2_projection_one_active
    ON book_ranking_v2_projection(book_id, topic_id) WHERE active;
CREATE INDEX book_ranking_v2_projection_topic_active
    ON book_ranking_v2_projection(topic_id, book_id) WHERE active;
CREATE TRIGGER book_ranking_v2_projection_updated BEFORE UPDATE ON book_ranking_v2_projection
FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

