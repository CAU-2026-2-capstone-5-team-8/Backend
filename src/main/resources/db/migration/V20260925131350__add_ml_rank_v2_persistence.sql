ALTER TABLE recommendation_item ADD CONSTRAINT recommendation_item_mode_shape CHECK (
    (
        ranking_mode = 'LEGACY_SCALAR'
        AND feature_id IS NOT NULL AND projection_id IS NULL
        AND score IS NOT NULL AND topic_fit IS NOT NULL
        AND vocabulary_fit IS NOT NULL AND knowledge_fit IS NOT NULL
        AND comprehension_fit IS NOT NULL
        AND vocabulary_requirement IS NOT NULL AND knowledge_requirement IS NOT NULL
        AND comprehension_requirement IS NOT NULL AND topic_relevance IS NOT NULL
        AND prerequisite_readiness IS NULL AND prerequisite_assessed_count IS NULL
        AND prerequisite_total_count IS NULL AND prerequisite_coverage IS NULL
        AND direct_learning_opportunity IS NULL AND direct_assessed_count IS NULL
        AND direct_total_count IS NULL AND direct_coverage IS NULL
        AND availability_status IS NULL AND covered_concepts IS NULL
        AND inferred_prerequisites IS NULL AND book_config_version IS NULL
        AND book_config_hash IS NULL
    )
    OR
    (
        ranking_mode = 'PREREQUISITE_FIRST_V2'
        AND feature_id IS NULL AND projection_id IS NOT NULL
        AND score IS NULL AND topic_fit IS NULL AND vocabulary_fit IS NULL
        AND knowledge_fit IS NULL AND comprehension_fit IS NULL
        AND vocabulary_requirement IS NULL AND knowledge_requirement IS NULL
        AND comprehension_requirement IS NULL AND topic_relevance IS NULL
        AND prerequisite_readiness IS NOT NULL
        AND prerequisite_assessed_count <= prerequisite_total_count
        AND abs(prerequisite_coverage - prerequisite_assessed_count::double precision / prerequisite_total_count) < 1e-9
        AND direct_assessed_count <= direct_total_count
        AND abs(direct_coverage - direct_assessed_count::double precision / direct_total_count) < 1e-9
        AND ((direct_assessed_count = 0) = (direct_learning_opportunity IS NULL))
        AND availability_status = 'personalizable'
        AND jsonb_typeof(covered_concepts) = 'array'
        AND jsonb_typeof(inferred_prerequisites) = 'array'
        AND book_config_version IS NOT NULL
        AND book_config_hash ~ '^sha256:[0-9a-f]{64}$'
    )
);
